export default function Sidebar({ locale }: { locale: string }) {
  const t = useTranslations("overview");
  const navT = useTranslations("nav");
  const pathname = usePathname();
  const { user } = useAuth();
  const role = user?.role;

  const nav = navItemsForRole(role ?? "");

  const isActive = (path: string) => {
    return pathname === `/${locale}${path}` || pathname === `/${locale}${path}/`;
  };

  return (
    <aside className="sidebar">
      <div className="brand">
        <svg width="28" height="28" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round">
          <path d="M12 22s8-4 8-10V5l-8-3-8 3v7c0 6 8 10 8 10z"></path>
        </svg>
        Ariba Shield
      </div>

      <ul className="nav-links">
        {Object.entries(nav).map(([section, items]) =>
          items.length === 0 ? null : (
            <li key={section}>
              <div className="sidebar-section-title" style={{ textTransform: "capitalize" }}>
                {section === "monitor" ? "Monitor" : section === "protect" ? "Protect" : navT("platform")}
              </div>
              {items.map((item) => {
                const label = item.labelKey === "overview" ? t("title") : navT(item.labelKey);
                return (
                  <Link key={item.href} href={`/${locale}${item.href === "/" ? "" : item.href}`}>
                    <li className={`nav-item ${isActive(item.href) ? "active" : ""}`}>
                      {ICONS[item.href]}
                      <span>{label}</span>
                    </li>
                  </Link>
                );
              })}
            </li>
          )
        )}
      </ul>
    </aside>
  );
}
